"""infra / ports —— 基础设施对上层承诺的抽象接口。

依赖倒置的接缝：Service 只认这里的 Protocol，不知道 JSON、文件系统或
``flet_video`` 的存在；具体实现放在 :mod:`cs_video_player.infra` 的适配器中，
由启动入口注入。

:class:`VideoControl` 是一个特例：原生播放器控件由 View 构造（它需要 cs-ui），
但操作方法以 Protocol 描述，于是 Infra 只面向能力编程，不反向依赖 View 的
具体类，也不 import 任何 UI 框架。
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any, Protocol, TypeVar

from cs_video_player.models.entities import MediaTrack, PlaylistItem

T = TypeVar("T")
ErrorHandler = Callable[[str, str], None]  # (label, raw_error)


class VideoControl(Protocol):
    """View 注入给基础设施的播放器能力（结构化类型，无框架依赖）。"""

    async def play(self) -> None: ...

    async def pause(self) -> None: ...

    async def play_or_pause(self) -> None: ...

    async def stop(self) -> None: ...

    async def seek(self, position_ms: int) -> None: ...

    async def seek_relative(self, delta_ms: int) -> None: ...

    async def jump_to(self, index: int) -> None: ...

    async def next(self) -> None: ...

    async def previous(self) -> None: ...

    async def play_at(
        self, index: int, tracks: tuple[MediaTrack, ...]
    ) -> None: ...

    async def restore_after_mode_change(
        self, position_ms: int, was_playing: bool
    ) -> None: ...

    async def seek_after_load(self, position_ms: int) -> None: ...

    async def take_screenshot(self) -> bytes | None: ...

    def set_volume(self, volume: float) -> None: ...

    def set_playback_rate(self, rate: float) -> None: ...

    def set_muted(self, muted: bool) -> None: ...

    def set_fullscreen(self, fullscreen: bool) -> None: ...

    def refresh(self) -> None: ...


class MediaPort(Protocol):
    """播放控制端口：Service 通过它下发播放意图。"""

    @property
    def bound(self) -> bool: ...

    def bind_control(self, control: VideoControl | None) -> None: ...

    def set_error_handler(self, handler: ErrorHandler | None) -> None: ...

    async def play(self) -> None: ...

    async def pause(self) -> None: ...

    async def play_or_pause(self) -> None: ...

    async def stop(self) -> None: ...

    async def seek(self, position_ms: int) -> None: ...

    async def seek_relative(self, delta_ms: int) -> None: ...

    async def jump_to(self, index: int) -> None: ...

    async def next(self) -> None: ...

    async def previous(self) -> None: ...

    async def play_at(
        self, index: int, tracks: tuple[MediaTrack, ...]
    ) -> None: ...

    async def restore_after_mode_change(
        self, position_ms: int, was_playing: bool
    ) -> None: ...

    async def seek_after_load(self, position_ms: int) -> None: ...

    async def take_screenshot(self) -> bytes | None: ...

    def set_volume(self, volume: float) -> None: ...

    def set_playback_rate(self, rate: float) -> None: ...

    def set_muted(self, muted: bool) -> None: ...

    def set_fullscreen(self, fullscreen: bool) -> None: ...


class PreferencesPort(Protocol):
    """本地持久化端口：设置、近期记录、会话。"""

    def load_recents(self) -> tuple[str, ...]: ...

    def save_recents(self, paths: tuple[str, ...]) -> None: ...

    def get_setting(self, key: str, default: T) -> T: ...

    def set_setting(self, key: str, value: object) -> None: ...

    def load_playback_states(self) -> dict[str, int]: ...

    def set_playback_state(self, path: str, position_ms: int) -> None: ...

    def load_session(self) -> dict[str, Any]: ...

    def save_session(self, data: dict[str, Any]) -> None: ...

    def clear_session(self) -> None: ...


class ScannerPort(Protocol):
    """文件系统端口：把路径翻译成播放列表项 / URI。"""

    def scan_videos(self, folder: str) -> tuple[PlaylistItem, ...]: ...

    def scan_videos_recursive(
        self, folder: str, max_depth: int = 3
    ) -> tuple[PlaylistItem, ...]: ...

    def make_playlist_item(self, path: str) -> PlaylistItem: ...

    def make_playlist_items(self, paths: tuple[str, ...]) -> tuple[PlaylistItem, ...]: ...

    def is_valid_video(self, path: str) -> bool: ...

    def count_videos(self, folder: str) -> int: ...

    def to_uri(self, path: str) -> str: ...
